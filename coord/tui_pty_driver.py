"""``tui-pty`` acceptance driver — Tier 2, real terminal (#3483).

Every black-box driver ``coord`` runs before this one drives the app
**in-process** (``tui-tuidriver`` goes through quadraui's ``TuiDriver``, a
Rust in-memory harness — see CLAUDE.md's coord-tui section). On 2026-09-29,
three real Windows TUI bugs all passed their in-process tests: a ~1 Hz
foreground flicker (vimcode#1634), activity-bar clicks doing nothing
(vimcode#1636), and slow right-click menus (vimcode#1635). The bytes an
in-process harness feeds the app are never generated by a real terminal, and
the bytes it reads back never pass through one either — so a whole class of
bug (idle repaint churn, real input translation, real paint latency) is
invisible to it by construction.

This module is that missing tier: it launches the repo's **real compiled
binary** under a **real pseudo-terminal** — a Unix ``pty`` via the stdlib
:mod:`pty` module on Linux/macOS (:class:`UnixPtyChild`), **ConPTY** on
Windows via the optional ``pywinpty`` package, the ``tui-pty`` extra's
Windows-only dependency (:class:`WindowsConPtyChild`) — sends real terminal
byte sequences (keys, SGR mouse including right-button and wheel), records
the raw output byte stream with timestamps, and feeds it through a VT
emulator (`pyte`, the ``tui-pty`` extra's cross-platform dependency) so
assertions can read the resulting screen grid (cell text and SGR
attributes).

**Smoke spec.** :func:`parse_smoke_spec` reads a platform-neutral YAML file,
checked into the *driven* repo (one file per app — the ``tui-pty`` analogue
of ``tui-tuidriver``'s ``tui/tests/acceptance.rs`` entrypoint; see
:func:`coord.acceptance_drivers._run_tui_pty`'s docstring for how its path
is threaded through as the driver's ``entrypoint:``). Steps:

- ``launch`` — spawn the real binary under the pty/ConPTY.
- ``key: <name>`` — send one key (named: ``enter``, ``esc``, ``tab``,
  ``backspace``, ``space``, arrow keys, ``home``/``end``, ``pageup``/
  ``pagedown``, ``delete``, ``insert``, ``f1``-``f12``, ``ctrl+<letter>``; or
  any single literal character).
- ``click: {row, col, button}`` — an SGR mouse click at 0-indexed
  ``(row, col)``; ``button`` is ``left`` (default), ``middle``, ``right``, or
  ``wheel-up``/``wheel-down`` (single-shot, no release event — mirrors a
  real wheel).
- ``wait_idle: {ms, timeout_ms}`` — block until the byte stream has been
  quiet for ``ms`` milliseconds, or fail after ``timeout_ms`` without ever
  reaching that quiet window (default 5000ms) — a precondition step, not an
  assertion on its own, but still fails the run if the app never settles.
- ``expect_screen: {region, text, attr}`` — the current VT screen (or a
  ``region: {row, col, width, height}`` sub-rectangle) must contain ``text``
  (a plain substring check against the rendered lines) and/or match
  ``attr: {row, col, <pyte Char field>: <expected value>}`` for one cell
  (e.g. ``{row: 3, col: 5, bold: true}``). At least one of ``text``/``attr``
  is required — a step with neither has nothing to assert against and
  could never fail, which :func:`parse_smoke_spec` rejects (#2096).
- ``expect_silent: {seconds}`` — the byte stream must receive **zero**
  bytes over a full ``seconds``-long real-time window. This is vimcode#1634's
  regression check: an idle app that's actually idle produces no repaint
  traffic; a ~1 Hz flicker does. See :meth:`SmokeRunner._do_expect_silent`
  for why this can only be answered by actually waiting out the window and
  re-reading a byte counter afterward, never by the mere absence of an
  exception (#2096: unconfirmed success is a defect).
- ``expect_within: {ms, text, region}`` — ``text`` must appear on the (VT)
  screen within ``ms`` milliseconds of this step starting; polls the live
  screen repeatedly rather than sampling once, so a slow-but-eventual paint
  still passes and a truly-never-appears one genuinely fails at the
  deadline (vimcode#1635's right-click-menu-latency regression check).

**The ``ESC[6n`` cursor-position query lesson (vimcode's own ConPTY tests,
folded in before this issue was dispatched).** ratatui's ``Terminal::new()``
blocks at startup on a Device Status Report reply to the ``ESC[6n`` it
sends — a real terminal answers this "where's the cursor" query
transparently; a driver standing in for one must too, or the app never
paints anything and every subsequent step times out waiting on a blank
screen. **On real Windows ConPTY, answering synchronously from inside the
byte-stream reader callback deadlocks the session** (verified by vimcode's
own ``tests/conpty_idle_flicker.rs``/``tests/conpty_activity_bar_click.rs`,
built with ``portable_pty`` + a ``vt100`` parser for exactly this tier).
:class:`SmokeRunner` therefore splits reading and replying across two
threads: ``_reader_loop`` only reads bytes, feeds the VT screen, and — on
spotting ``ESC[6n`` — enqueues a reply; a separate ``_responder_loop``
dequeues and writes it. Never write the child's stdin from the reader
thread itself.

**What this tier does NOT see** (spelled out in the issue, and important —
see vimcode#3484 for the tier this hands off to): raw ConPTY was not the
last mile for any of the three Windows bugs above. All three *passed* under
a raw ConPTY too — the idle byte stream is genuinely silent (#1634), a
right-click paints in about 50µs measured this way (#1635), activity-bar
clicks work (#1636) — yet the operator still saw flicker, lag and dead
clicks in a real terminal *window*. This driver proves the app's own
behaviour is correct against a real pty; it cannot see a terminal
emulator's own rendering/input-translation behaviour (Windows Terminal,
legacy conhost, iTerm, GNOME Terminal) — that needs a native kind driving
and capturing an actual terminal window (vimcode#3484).
"""

from __future__ import annotations

import os
import queue
import re
import subprocess
import threading
